CREATE TABLE IF NOT EXISTS users (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(120) NOT NULL,
  email VARCHAR(190) NOT NULL UNIQUE,
  password VARCHAR(255) NOT NULL,
  phone VARCHAR(40) NULL,
  is_admin TINYINT(1) NOT NULL DEFAULT 0,
  experience_tier ENUM('fresher','professional','power') NOT NULL DEFAULT 'fresher',
  experience_years TINYINT UNSIGNED NULL,
  profession VARCHAR(160) NULL,
  category VARCHAR(120) NULL,
  is_premium TINYINT(1) NOT NULL DEFAULT 0,
  plan VARCHAR(40) NULL,
  plan_expires_at DATETIME NULL,
  marketing_consent TINYINT(1) NOT NULL DEFAULT 0,
  last_ats_at DATETIME NULL,
  last_checkout_at DATETIME NULL,
  abandoned_sent_at DATETIME NULL,
  referred_by INT UNSIGNED NULL,
  referral_code VARCHAR(24) NOT NULL UNIQUE,
  created_at DATETIME NOT NULL,
  updated_at DATETIME NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS settings (
  k VARCHAR(80) PRIMARY KEY,
  v LONGTEXT NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS mailboxes (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  label VARCHAR(120) NOT NULL,
  purpose ENUM('transactional','marketing') NOT NULL DEFAULT 'marketing',
  host VARCHAR(190) NOT NULL,
  port SMALLINT UNSIGNED NOT NULL DEFAULT 587,
  username VARCHAR(190) NOT NULL,
  password_enc TEXT NOT NULL,
  encryption VARCHAR(16) NOT NULL DEFAULT 'tls',
  from_name VARCHAR(120) NOT NULL,
  from_email VARCHAR(190) NOT NULL,
  enabled TINYINT(1) NOT NULL DEFAULT 1,
  last_used_at DATETIME NULL,
  created_at DATETIME NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS leads (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  email VARCHAR(190) NOT NULL,
  name VARCHAR(120) NULL,
  source VARCHAR(80) NOT NULL DEFAULT 'opt-in',
  status VARCHAR(40) NOT NULL DEFAULT 'new',
  campaign_step INT NOT NULL DEFAULT 1,
  last_sent_at DATETIME NULL,
  stop_marketing TINYINT(1) NOT NULL DEFAULT 0,
  consent_at DATETIME NULL,
  consent_note VARCHAR(255) NULL,
  unsubscribe_token VARCHAR(64) NOT NULL UNIQUE,
  created_at DATETIME NOT NULL,
  UNIQUE KEY leads_email_source (email, source),
  KEY leads_campaign_idx (status, stop_marketing, campaign_step)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS tailor_credits (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  user_id INT UNSIGNED NOT NULL UNIQUE,
  total_allowed INT UNSIGNED NOT NULL DEFAULT 3,
  used_count INT UNSIGNED NOT NULL DEFAULT 0,
  remaining_balance INT UNSIGNED NOT NULL DEFAULT 3,
  CONSTRAINT fk_credits_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS wallet_entries (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  user_id INT UNSIGNED NOT NULL,
  type ENUM('credit','debit','hold','payout') NOT NULL,
  amount_paise INT NOT NULL,
  status ENUM('pending','available','paid','cancelled') NOT NULL DEFAULT 'pending',
  hold_until DATETIME NULL,
  note VARCHAR(255) NULL,
  created_at DATETIME NOT NULL,
  KEY wallet_user_idx (user_id, status),
  CONSTRAINT fk_wallet_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS resumes (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  user_id INT UNSIGNED NOT NULL,
  title VARCHAR(180) NOT NULL,
  content_json LONGTEXT NOT NULL,
  updated_at DATETIME NOT NULL,
  CONSTRAINT fk_resume_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS ats_scans (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  user_id INT UNSIGNED NULL,
  job_title VARCHAR(180) NULL,
  job_text LONGTEXT NOT NULL,
  resume_text LONGTEXT NOT NULL,
  score TINYINT UNSIGNED NOT NULL,
  report_json LONGTEXT NOT NULL,
  created_at DATETIME NOT NULL,
  KEY ats_user_idx (user_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS applications (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  user_id INT UNSIGNED NOT NULL,
  company VARCHAR(160) NOT NULL,
  role VARCHAR(160) NOT NULL,
  stage ENUM('saved','applied','interview','offer') NOT NULL DEFAULT 'saved',
  next_action VARCHAR(255) NULL,
  resume_id INT UNSIGNED NULL,
  created_at DATETIME NOT NULL,
  CONSTRAINT fk_app_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS purchases (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  user_id INT UNSIGNED NOT NULL,
  plan VARCHAR(40) NOT NULL,
  amount_paise INT UNSIGNED NOT NULL,
  credits_addon INT UNSIGNED NOT NULL DEFAULT 0,
  status VARCHAR(40) NOT NULL DEFAULT 'started',
  provider VARCHAR(40) NOT NULL DEFAULT 'razorpay',
  payment_reference VARCHAR(120) NULL,
  is_live TINYINT(1) NOT NULL DEFAULT 0,
  access_until DATETIME NULL,
  created_at DATETIME NOT NULL,
  KEY purchase_user_idx (user_id, status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS email_jobs (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  recipient VARCHAR(190) NOT NULL,
  trigger_name VARCHAR(80) NOT NULL,
  subject VARCHAR(180) NOT NULL,
  body LONGTEXT NOT NULL,
  status VARCHAR(40) NOT NULL DEFAULT 'queued',
  due_at DATETIME NOT NULL,
  sent_at DATETIME NULL,
  error TEXT NULL,
  mailbox_id INT UNSIGNED NULL,
  created_at DATETIME NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS pages (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  slug VARCHAR(180) NOT NULL UNIQUE,
  type ENUM('Guide','Calculator','Legal') NOT NULL DEFAULT 'Guide',
  title VARCHAR(180) NOT NULL,
  category VARCHAR(80) NOT NULL,
  description VARCHAR(500) NOT NULL,
  body LONGTEXT NULL,
  keywords VARCHAR(500) NULL,
  published TINYINT(1) NOT NULL DEFAULT 1,
  updated_at DATETIME NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS coupons (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  code VARCHAR(30) NOT NULL UNIQUE,
  type ENUM('percent','fixed') NOT NULL DEFAULT 'percent',
  value INT UNSIGNED NOT NULL,
  expires_at DATE NULL,
  enabled TINYINT(1) NOT NULL DEFAULT 1,
  plans_json VARCHAR(255) NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS events (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  user_id INT UNSIGNED NULL,
  event VARCHAR(80) NOT NULL,
  path VARCHAR(190) NULL,
  created_at DATETIME NOT NULL,
  KEY events_day_idx (created_at, event)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS reviews (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  public_id VARCHAR(32) NOT NULL UNIQUE,
  name VARCHAR(80) NOT NULL,
  city VARCHAR(60) NULL,
  role VARCHAR(80) NULL,
  rating TINYINT UNSIGNED NOT NULL,
  body VARCHAR(600) NOT NULL,
  source VARCHAR(40) NOT NULL,
  status ENUM('pending','published','hidden') NOT NULL DEFAULT 'pending',
  created_at DATETIME NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS password_resets (
  email VARCHAR(190) PRIMARY KEY,
  token VARCHAR(64) NOT NULL,
  created_at DATETIME NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
